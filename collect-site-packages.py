#!/usr/bin/env python3
"""Copy exactly the site-packages Deluge needs into the bundle.

deploy.sh used to copy *all* of MSYS2's site-packages minus a short exclude
list. That denylist silently ships whatever else happens to be installed in
MSYS2: by 2026-11 it had picked up OpenEXR's Python bindings (imath, 34 MB with
libPyImath), VapourSynth and Meson - 44 MB of unrelated code plus the DLLs
ntldd then dragged in for their extension modules.

This builds an allowlist instead: the requirement closure of Deluge (with its
"all" extra), PyGObject, pycairo and the runtime pieces pkg_resources needs,
resolved from each distribution's own metadata, and copies the files each
distribution's RECORD lists. A few things carry no usable RECORD and are named
explicitly below, each with the reason.

Usage (inside the MSYS2 CLANGARM64 shell, run by deploy.sh):
    python collect-site-packages.py <dest site-packages dir>
"""

import os
import re
import shutil
import sys
import sysconfig
from importlib import metadata

from packaging.markers import default_environment
from packaging.requirements import Requirement

SITE = sysconfig.get_path('platlib')

# (distribution, extras to activate). Deluge's own requirements pull in
# Twisted[tls], pyOpenSSL, pywin32 (the shim) and the rest.
ROOTS = [
    ('deluge', {'all'}),  # setproctitle, pillow, chardet, ifaddr
    ('PyGObject', set()),  # GTK UI; Deluge does not declare it
    ('pycairo', set()),  # used by the GTK UI through gi
    ('jaraco.text', set()),  # imported by pkg_resources
    ('packaging', set()),  # imported by pkg_resources
]

# Requirements deliberately not followed. Each has shipped without problems.
PRUNE = {
    # jaraco.text requires typer only for its two CLI scripts
    # (show-newlines, strip-prefix); pkg_resources uses none of them.
    'typer-slim': 'jaraco.text CLI only; pkg_resources never imports it',
}

# Distributions whose RECORD is empty (MSYS2 builds PyGObject and pycairo with
# meson, which writes none; the pywin32 shim is hand-made) and that have no
# top_level.txt to fall back on.
TOP_LEVEL_FALLBACK = {
    'pygobject': ['gi'],
    'pycairo': ['cairo'],
}

# Not owned by any distribution at all.
UNOWNED = [
    'pkg_resources',  # extracted from the setuptools 80.9.0 wheel; see install-deluge.sh
    'libtorrent.egg-info',  # built by build-libtorrent.sh
]
UNOWNED_GLOBS = [
    re.compile(r'^libtorrent\..*\.pyd$'),  # built by build-libtorrent.sh
]

# Bytecode is rebuilt at run time. direct_url.json is pip's record of where a
# distribution was installed from - for Deluge, the sdist folder inside this
# checkout - so it means nothing in the bundle and would make it path-dependent.
SKIP = re.compile(r'(^|/)__pycache__(/|$)|\.pyc$|(^|/)direct_url\.json$')


def canon(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def resolve():
    """Return {canonical name: Distribution} for the whole closure."""
    env = default_environment()
    seen, todo = {}, list(ROOTS)
    while todo:
        name, extras = todo.pop()
        key = canon(name)
        if key in PRUNE:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            sys.exit('required distribution not installed: %s' % name)
        prev = seen.get(key)
        if prev and extras <= prev[1]:
            continue
        extras = extras | (prev[1] if prev else set())
        seen[key] = (dist, extras)
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker:
                active = any(
                    req.marker.evaluate(dict(env, extra=e)) for e in ({''} | extras)
                )
                if not active:
                    continue
            todo.append((req.name, set(req.extras)))
    return {k: v[0] for k, v in seen.items()}


def dist_files(dist):
    """Paths, relative to site-packages, that belong to a distribution."""
    files = [str(f).replace(os.sep, '/') for f in (dist.files or [])]
    files = [f for f in files if not f.startswith('../')]  # bin/ scripts
    # The .dist-info dir itself. `_path` is private, but it is the only handle
    # on a distribution with no RECORD at all (dist.files is then None).
    meta_dir = os.path.basename(str(dist._path))
    if any(not f.startswith(meta_dir + '/') for f in files):
        return files
    # RECORD is empty or lists only its own metadata: fall back to top_level.txt,
    # then to the explicit map.
    tops = (dist.read_text('top_level.txt') or '').split()
    tops = tops or TOP_LEVEL_FALLBACK.get(canon(dist.metadata['Name']), [])
    if not tops:
        sys.exit('no file list for %s' % dist.metadata['Name'])
    out = [meta_dir]
    for t in tops:
        for cand in (t, t + '.py'):
            if os.path.exists(os.path.join(SITE, cand)):
                out.append(cand)
        out += [e for e in os.listdir(SITE) if e.startswith(t + '.') and e.endswith('.pyd')]
    return out


def expand(rel):
    """Yield files under rel (a file or a directory), relative to SITE."""
    full = os.path.join(SITE, rel)
    if os.path.isdir(full):
        for dp, _, fs in os.walk(full):
            for f in fs:
                yield os.path.relpath(os.path.join(dp, f), SITE).replace(os.sep, '/')
    elif os.path.isfile(full):
        yield rel


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: %s <dest site-packages dir>' % sys.argv[0])
    dest = sys.argv[1]

    dists = resolve()
    wanted = set()
    for dist in dists.values():
        for rel in dist_files(dist):
            wanted.update(expand(rel))
    for rel in UNOWNED:
        found = list(expand(rel))
        if not found:
            sys.exit('expected but missing: %s' % rel)
        wanted.update(found)
    for rx in UNOWNED_GLOBS:
        hits = [e for e in os.listdir(SITE) if rx.match(e)]
        if not hits:
            sys.exit('expected but missing: %s' % rx.pattern)
        wanted.update(hits)

    total = 0
    for rel in sorted(wanted):
        if SKIP.search(rel):
            continue
        src = os.path.join(SITE, rel)
        dst = os.path.join(dest, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        total += os.path.getsize(src)

    names = sorted(d.metadata['Name'] for d in dists.values())
    print('    %d distributions: %s' % (len(names), ', '.join(names)))
    print('    pruned: %s' % ', '.join('%s (%s)' % kv for kv in PRUNE.items()))
    print('    %d files, %.1f MB' % (len(wanted), total / 1048576))


if __name__ == '__main__':
    main()
